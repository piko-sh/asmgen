package asmgen

import (
	"strings"
)

const (
	// defaultGeneratedByTool is the tool name placed in the "Code generated by <tool>; DO
	// NOT EDIT." marker when no override is supplied.
	defaultGeneratedByTool = "asmgen"
)

// generateConfig holds the resolved generation options shared by GenerateFiles and
// GenerateAndValidate. Both must resolve options identically so that validation compares
// against byte-identical generated output.
type generateConfig struct {
	// generatedByTool is the tool name embedded in the generated-code marker.
	generatedByTool string

	// fileHeader is an optional comment block appended below the generated-code marker at
	// the top of every generated .s file, with trailing newlines normalised away.
	fileHeader string
}

// Option configures assembly file generation. The same options must be passed to
// GenerateFiles and GenerateAndValidate so that generation and validation agree on the
// exact bytes to emit.
type Option func(*generateConfig)

// newGenerateConfig resolves a set of options into a generateConfig, applying defaults
// first so unset fields fall back to library defaults.
//
// Takes opts ([]Option) which are the caller-supplied options, applied in order.
//
// Returns generateConfig with all options applied.
func newGenerateConfig(opts []Option) generateConfig {
	cfg := generateConfig{generatedByTool: defaultGeneratedByTool}
	for _, opt := range opts {
		opt(&cfg)
	}
	return cfg
}

// WithGeneratedByTool overrides the tool name embedded in the "Code generated by <tool>;
// DO NOT EDIT." marker emitted at the top of every generated .s file.
//
// The default is "asmgen". Consuming projects whose generator binary has a different name
// (for example a "cmd/asmgen" wrapper) should set this so the marker matches their tooling.
//
// Takes tool (string) which is the tool name to embed in the marker.
//
// Returns Option which applies the override.
func WithGeneratedByTool(tool string) Option {
	return func(cfg *generateConfig) { cfg.generatedByTool = tool }
}

// WithFileHeader sets a comment block appended immediately below the generated-code marker
// at the top of every generated .s file — typically the consuming project's copyright,
// licence, and any additional banner text.
//
// The block should be a sequence of "//"-prefixed lines. A trailing newline is optional;
// surrounding blank lines are normalised so the block sits one blank line below the marker
// and one blank line above the //go:build constraint. Empty by default, in which case only
// the generated-code marker is emitted.
//
// Takes header (string) which is the comment block to append.
//
// Returns Option which applies the header.
func WithFileHeader(header string) Option {
	return func(cfg *generateConfig) { cfg.fileHeader = strings.TrimRight(header, "\n") }
}
