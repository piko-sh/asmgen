package asmgen

import (
	"strings"
)

const (
	// defaultGeneratedByTool is the tool name placed in the "Code generated by <tool>; DO
	// NOT EDIT." marker when no override is supplied.
	defaultGeneratedByTool = "asmgen"
)

// generateConfig holds the resolved generation options shared by GenerateFiles and
// GenerateAndValidate. Both must resolve options identically so that validation compares
// against byte-identical generated output.
type generateConfig struct {
	// generatedByTool is the tool name embedded in the generated-code marker.
	generatedByTool string

	// fileHeader is an optional comment block appended below the generated-code marker at
	// the top of every generated .s file, with trailing newlines normalised away.
	fileHeader string
}

// Option configures assembly file generation. The same options must be passed to
// GenerateFiles and GenerateAndValidate so that generation and validation agree on the
// exact bytes to emit.
type Option func(*generateConfig)

// newGenerateConfig applies options over the library defaults.
//
// Takes options ([]Option) which are the caller-supplied options, applied in order.
//
// Returns generateConfig with all options applied.
func newGenerateConfig(options []Option) generateConfig {
	config := generateConfig{generatedByTool: defaultGeneratedByTool, fileHeader: ""}
	for _, option := range options {
		option(&config)
	}
	return config
}

// WithGeneratedByTool sets the generator name in the generated-file marker.
//
// The default is "asmgen".
//
// Takes tool (string) which is the tool name to embed in the marker.
//
// Returns Option which applies the override.
func WithGeneratedByTool(tool string) Option {
	return func(config *generateConfig) { config.generatedByTool = tool }
}

// WithFileHeader sets the comment block below the generated-file marker.
//
// Takes header (string) which contains "//"-prefixed lines, or is empty for no header.
//
// Returns Option which applies the header.
func WithFileHeader(header string) Option {
	return func(config *generateConfig) { config.fileHeader = strings.TrimRight(header, "\n") }
}
