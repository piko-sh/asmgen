// strip others of their rights and dignity.`

func generateOneS(t *testing.T, opts ...Option) string {
	t.Helper()
	writer := newMemWriter()
	group := minimalGroup("foo")
	err := GenerateFiles(writer, []*testArch{newAMD64Arch()}, []FileGroup[*testArch]{group}, nil, nil, opts...)
	require.NoError(t, err)
	return string(writer.files[filepath.Join("out", "foo_amd64.s")])
}

func TestGenerateFiles_DefaultHeaderIsNeutralMarkerOnly(t *testing.T) {
	t.Parallel()

	content := generateOneS(t)

	assert.True(t, strings.HasPrefix(content, "// Code generated by asmgen; DO NOT EDIT.\n\n//go:build"),
		"default header should be the neutral generated-code marker only, got:\n%s", content)
	assert.NotContains(t, content, "Copyright", "default header must not carry any project copyright")
	assert.NotContains(t, content, "fascism", "default header must not carry any project banner")
}

func TestGenerateFiles_GeneratedByToolOverride(t *testing.T) {
	t.Parallel()

	content := generateOneS(t, WithGeneratedByTool("cmd/asmgen"))

	assert.True(t, strings.HasPrefix(content, "// Code generated by cmd/asmgen; DO NOT EDIT.\n"),
		"marker should carry the overridden tool name, got:\n%s", content)
}

func TestGenerateFiles_ReproducesPikoHeaderExactly(t *testing.T) {
	t.Parallel()

	content := generateOneS(t, WithGeneratedByTool("cmd/asmgen"), WithFileHeader(pikoFileHeader))

	wantPrefix := "// Code generated by cmd/asmgen; DO NOT EDIT.\n\n" + pikoFileHeader + "\n\n//go:build"
	assert.True(t, strings.HasPrefix(content, wantPrefix),
		"header must reproduce piko's original block byte-for-byte, got:\n%s", content)
}

func TestWithFileHeader_NormalisesTrailingNewlines(t *testing.T) {
	t.Parallel()

	assert.Equal(t,
		generateOneS(t, WithFileHeader("// hi")),
		generateOneS(t, WithFileHeader("// hi\n\n\n")),
		"trailing newlines in the supplied header must be normalised away")
}
